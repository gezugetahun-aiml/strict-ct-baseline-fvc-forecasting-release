#!/usr/bin/env python3
"""Recompute manuscript metrics and reviewer diagnostics from a local OOF CSV.

The OOF CSV is generated by the frozen final-v10 model and may contain source
patient identifiers. Keep it in local_outputs/ and do not commit it.
"""
from pathlib import Path
import argparse
import numpy as np
import pandas as pd

def main():
    ap=argparse.ArgumentParser(); ap.add_argument('--oof',required=True,type=Path); args=ap.parse_args()
    df=pd.read_csv(args.oof)
    y=df.TargetFVC.to_numpy(float); p=df.PredFVC.to_numpy(float)
    sigma=np.maximum(df.PredSigma.to_numpy(float),70.0); err=p-y; ae=np.abs(err)
    delta=np.minimum(ae,1000.0)
    lll=np.mean(-(np.sqrt(2.0)*delta/sigma + np.log(np.sqrt(2.0)*sigma)))
    print(f'Patients: {df.Patient.nunique()}')
    print(f'Targets: {len(df)}')
    print(f'MAE: {ae.mean():.12f} mL')
    print(f'RMSE: {np.sqrt(np.mean(err**2)):.12f} mL')
    print(f'LLL: {lll:.15f}')
    print(f'Mean sigma: {df.PredSigma.mean():.12f} mL')
    print(f'N(|error|>=500 mL): {(ae>=500).sum()}')
    expert_cols=[c for c in df.columns if c.startswith('Expert_')]
    if expert_cols:
        A=df[expert_cols].to_numpy(float); idx=np.argmin(np.abs(A-y[:,None]),axis=1)
        oracle=A[np.arange(len(df)),idx]
        oe=oracle-y; per=df.Expert_Persistence.to_numpy(float)-y
        print(f'Persistence MAE/RMSE: {np.mean(np.abs(per)):.6f} / {np.sqrt(np.mean(per**2)):.6f} mL')
        print(f'Oracle MAE/RMSE: {np.mean(np.abs(oe)):.6f} / {np.sqrt(np.mean(oe**2)):.6f} mL')
        cat=ae>=500; lo=A[cat].min(1); hi=A[cat].max(1); yy=y[cat]
        print(f'Catastrophic targets outside expert range: {np.sum((yy<lo)|(yy>hi))}/{cat.sum()}')
        print(f'Catastrophic cases still >=500 mL under oracle: {(np.abs(oracle[cat]-yy)>=500).sum()}/{cat.sum()}')

if __name__=='__main__': main()
